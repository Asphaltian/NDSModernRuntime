namespace NTRModern;

/// <summary>Which DS the game runs on. Keep in mind that some games behave a little differently on each of them.</summary>
public enum Model
{
    /// <summary>The original Nintendo DS.</summary>
    DS,

    /// <summary>The Nintendo DS Lite.</summary>
    DSLite,

    /// <summary>The Nintendo DSi, running the game the same way it runs any DS cartridge.</summary>
    DSi,
}
